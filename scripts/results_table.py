#!/usr/bin/env python3
"""
results.txt: every measured and computed number, one row per (case, n, w),
space separated and aligned.

  case     solver, as in cases.txt (permnet72 = permnet72-greedy)
  n        cube size
  w        0 = the plotted value: the chosen (best measured) strip width,
           or the only one (rcube1d), or brobdicube's planner widths;
           w > 0 = a width tried by the tune step but not chosen
  width    the strip width actually used by the w = 0 row (0 = planner)
  moves    mean center moves over all pooled solves ('-' = not measured)
  stderr   standard error of that mean
  samples  number of solves pooled
  worst    worst-case bound (w = 0 rows only): brobdicube -w for the
           brobdicube cases, scripts/bounds.py / permnet_bounds.py otherwise
  model    brobdicube planner's expected average (brobdicube cases only)

Usage: results_table.py [--out FILE]
"""
import argparse
import csv
import glob
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import run_others as ro                                  # noqa: E402
from run_brobdicube import pooled                        # noqa: E402
import permnet_bounds                                    # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'data')

# case name -> data directory
CASES = [('rcube1d', 'rcube1d'), ('rcube2d', 'rcube2d'), ('sortnet96', 'sortnet96'),
         ('permnet72-greedy', 'permnet72'), ('permnet72-optimal', 'permnet72-optimal')]
for _l in (67, 66, 65, 64, 63, 62):
    CASES += [('permnet%d-%s' % (_l, m), 'permnet%d-%s' % (_l, m)) for m in ('greedy', 'optimal')]
for _x in 'WAB':
    CASES += [('permnet61%s-%s' % (_x, m), 'permnet61%s-%s' % (_x, m)) for m in ('greedy', 'optimal')]
CASES.append(('brobdicube', 'brobdicube'))


def series(path, col='moves'):
    if not os.path.exists(path):
        return {}
    return {int(r['n']): r.get(col) for r in csv.DictReader(open(path))}


def worst_of(case, d):
    if case.startswith('permnet6') and not case.startswith('permnet61'):
        net = case.split('-')[0]
        return lambda n: permnet_bounds.bound(net, n)[0]
    if case == 'permnet72-optimal':
        d = 'permnet72'          # every stage is used in both modes
    # brobdicube -w: the exact integer column ('moves' is rounded to 15 digits)
    p = os.path.join(DATA, d, 'worst.csv')
    s = {n: v for n, v in series(p, 'exact').items() if v} or series(p) or \
        series(os.path.join(DATA, d, 'upper.csv'))
    return lambda n: s.get(n, '-')


def fmt(x):
    if isinstance(x, float):
        return '%.10g' % x
    return str(x)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'results.txt'))
    a = ap.parse_args()
    head = ['case', 'n', 'w', 'width', 'moves', 'stderr', 'samples', 'worst', 'model']
    rows = []
    for case, d in CASES:
        runs = []
        for p in sorted(glob.glob(os.path.join(DATA, d, 'runs', 'sim*.csv'))):
            runs += list(csv.DictReader(open(p)))
        byn = {}
        for r in runs:
            byn.setdefault(int(r['n']), {}).setdefault(int(r.get('w', 0)), []).append(r)
        worst = worst_of(case, d)
        model = series(os.path.join(DATA, d, 'model.csv'))
        ns = set(byn) | set(series(os.path.join(DATA, d, 'worst.csv'))) | \
            set(series(os.path.join(DATA, d, 'upper.csv'))) | set(model)
        if case.startswith('permnet6') and not case.startswith('permnet61'):
            ns |= set(series(os.path.join(DATA, 'permnet72', 'upper.csv')))
        solver = d if d in ro.SOLVERS else None
        for n in sorted(ns):
            ws = byn.get(n, {})
            chosen = ro.width(solver, n) if solver else 0
            if solver and ro.SOLVERS[solver].widths == ro.TUNE and ws and chosen not in ws:
                chosen = min(ws, key=lambda w: pooled(ws[w])[0])
            for w in [chosen] + sorted(x for x in ws if x != chosen):
                rs = ws.get(w)
                if rs:
                    mean, sd, N = pooled(rs)
                    se = sd / math.sqrt(N) if N > 1 else float('nan')
                    meas = ['%.10g' % mean, '%.4g' % se if N > 1 else '-', N]
                else:
                    meas = ['-', '-', '-']
                if w == chosen:
                    rows.append([case, n, 0, chosen] + meas + [worst(n), model.get(n, '-')])
                else:
                    rows.append([case, n, w, w] + meas + ['-', '-'])
    rows = [[fmt(x) for x in r] for r in rows]
    wid = [max(len(r[i]) for r in rows + [head]) for i in range(len(head))]
    with open(a.out, 'w') as f:
        doc = __doc__.strip().split('Usage:')[0].rstrip()
        f.write(''.join('# ' + line + '\n' for line in doc.split('\n')))
        f.write('# (generated by scripts/results_table.py from data/*/runs)\n')
        f.write(' '.join(h.ljust(wid[i]) if i == 0 else h.rjust(wid[i]) for i, h in enumerate(head)).rstrip() + '\n')
        for r in rows:
            f.write(' '.join(x.ljust(wid[i]) if i == 0 else x.rjust(wid[i]) for i, x in enumerate(r)).rstrip() + '\n')
    print('%s: %d rows' % (a.out, len(rows)))


if __name__ == '__main__':
    main()
