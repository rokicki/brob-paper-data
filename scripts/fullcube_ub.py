#!/usr/bin/env python3
"""
fullcube_ub.txt: worst-case upper bounds on the move count for solving the
whole n x n x n cube (centers, wings, middle edges and corners), for every
size brobdicube's worst-case planner (-w) was run at, space separated.

  case     brobdicube (full algorithm library), or permnet61W / 61A / 61B
           (brobdicube -D nets/...; -g and -O give the same worst case,
           which is checked)
  n        cube size (even)
  centers  C(n): brobdicube -w center moves, exact integer (column exact of
           data/<case>/worst.csv; the planner output, with the
           "Exact worst-case cost" line, is in data/<case>/runs/worst.out)
  wings    wings_ub(n), Equation (wings-ub), including the n/2-1 parity
           slice moves (scripts/common.py)
  ec       middle edges and corners: 20, the 3x3x3 diameter (the solver's
           own two-phase step uses at most 11 + 14 = 25)
  total    centers + wings + ec, as total_ub(n) in the paper

Usage: fullcube_ub.py [--out FILE]
"""
import argparse
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import wings_ub                              # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'data')
EC = 20

# case -> data directories whose worst.csv must agree
CASES = [('brobdicube', ['brobdicube'])] + \
    [('permnet61' + x, ['permnet61%s-%s' % (x, m) for m in ('greedy', 'optimal')])
     for x in 'WAB']


def worst(d):
    p = os.path.join(DATA, d, 'worst.csv')
    if not os.path.exists(p):
        return {}
    r = {}
    for row in csv.DictReader(open(p)):
        if not row.get('exact'):
            sys.exit('%s: no exact worst case for n=%s (rerun the -w planning)' % (p, row['n']))
        r[int(row['n'])] = int(row['exact'])
    return r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'fullcube_ub.txt'))
    a = ap.parse_args()
    head = ['case', 'n', 'centers', 'wings', 'ec', 'total']
    rows = []
    for case, dirs in CASES:
        ws = [worst(d) for d in dirs]
        ws = [w for w in ws if w]
        if not ws:
            continue
        for w in ws[1:]:
            if w != ws[0]:
                sys.exit('%s: worst cases differ between %s' % (case, ', '.join(dirs)))
        for n, c in sorted(ws[0].items()):
            if n % 2:
                sys.exit('%s n=%d: odd size' % (case, n))
            wu = wings_ub(n)
            rows.append([case, n, c, wu, EC, c + wu + EC])
    rows = [[str(x) for x in r] for r in rows]
    wid = [max(len(r[i]) for r in rows + [head]) for i in range(len(head))]
    with open(a.out, 'w') as f:
        doc = __doc__.strip().split('Usage:')[0].rstrip()
        f.write(''.join('# ' + line + '\n' for line in doc.split('\n')))
        f.write('# (generated by scripts/fullcube_ub.py)\n')
        f.write(' '.join(h.ljust(wid[i]) if i == 0 else h.rjust(wid[i]) for i, h in enumerate(head)).rstrip() + '\n')
        for r in rows:
            f.write(' '.join(x.ljust(wid[i]) if i == 0 else x.rjust(wid[i]) for i, x in enumerate(r)).rstrip() + '\n')
    print('%s: %d rows' % (a.out, len(rows)))


if __name__ == '__main__':
    main()
